-- TABLAS MAESTRAS
CREATE TABLE USUARIOS (
    USUARIO_ID BIGINT GENERATED BY DEFAULT AS IDENTITY, 
    USERNAME VARCHAR(50) NOT NULL,
    PASSWORD VARCHAR(255) NOT NULL,
    CORREO VARCHAR(255) NOT NULL,
    NOMBRE VARCHAR(100) NOT NULL,
    APELLIDOS VARCHAR(100) NOT NULL,
    EDAD SMALLINT,
    GENERO SMALLINT,
    ESTADO SMALLINT DEFAULT 1,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FECHA_MODIFICACION TIMESTAMP,
    CONSTRAINT PK_USUARIOS PRIMARY KEY (USUARIO_ID),
    CONSTRAINT UQ_USUARIOS_USERNAME UNIQUE (USERNAME), 
    CONSTRAINT UQ_USUARIOS_CORREO UNIQUE (CORREO)
);

CREATE TABLE ROLES (
    ROL_ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR(100) NOT NULL,
    PERSPECTIVA VARCHAR(255),
    ESTADO SMALLINT DEFAULT 1,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FECHA_MODIFICACION TIMESTAMP,
    CONSTRAINT PK_ROLES PRIMARY KEY (ROL_ID),
    CONSTRAINT UQ_ROLES_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE PERMISOS (
    PERMISO_ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR(100) NOT NULL,
    PERSPECTIVA VARCHAR(255),
    ESTADO SMALLINT DEFAULT 1,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FECHA_MODIFICACION TIMESTAMP,
    CONSTRAINT PK_PERMISOS PRIMARY KEY (PERMISO_ID),
    CONSTRAINT UQ_PERMISOS_NOMBRE UNIQUE (NOMBRE)
);

-- TABLAS PUENTE (Relaciones N:M)
CREATE TABLE USUARIOS_ROLES (
    USUARIO_ID BIGINT NOT NULL,
    ROL_ID BIGINT NOT NULL,
    ESTADO SMALLINT DEFAULT 1,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FECHA_MODIFICACION TIMESTAMP,
    CONSTRAINT PK_USUARIOS_ROLES PRIMARY KEY (USUARIO_ID, ROL_ID),
    CONSTRAINT FK_USU_ROL_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS(USUARIO_ID) ON DELETE CASCADE,
    CONSTRAINT FK_USU_ROL_ROL FOREIGN KEY (ROL_ID) REFERENCES ROLES(ROL_ID) ON DELETE CASCADE
);

CREATE TABLE ROLES_PERMISOS (
    ROL_ID BIGINT NOT NULL,
    PERMISO_ID BIGINT NOT NULL,
    ESTADO SMALLINT DEFAULT 1,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FECHA_MODIFICACION TIMESTAMP,
    CONSTRAINT PK_ROLES_PERMISOS PRIMARY KEY (ROL_ID, PERMISO_ID),
    CONSTRAINT FK_ROL_PER_ROL FOREIGN KEY (ROL_ID) REFERENCES ROLES(ROL_ID) ON DELETE CASCADE,
    CONSTRAINT FK_ROL_PER_PERMISO FOREIGN KEY (PERMISO_ID) REFERENCES PERMISOS(PERMISO_ID) ON DELETE CASCADE
);

-- ÍNDICES ADICIONALES PARA OPTIMIZAR JOINS
CREATE INDEX IDX_USUARIOS_ROLES_ROL ON USUARIOS_ROLES(ROL_ID);
CREATE INDEX IDX_ROLES_PERMISOS_PERMISO ON ROLES_PERMISOS(PERMISO_ID);

