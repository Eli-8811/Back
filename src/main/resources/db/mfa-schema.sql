CREATE TABLE IF NOT EXISTS USUARIO_MFA (
    USUARIO_ID BIGINT PRIMARY KEY REFERENCES USUARIO (USUARIO_ID) ON DELETE CASCADE,
    SECRET_ENCRYPTED TEXT NOT NULL,
    LAST_TOTP_STEP BIGINT NOT NULL,
    CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS USUARIO_MFA_RECOVERY_CODE (
    USUARIO_ID BIGINT NOT NULL REFERENCES USUARIO_MFA (USUARIO_ID) ON DELETE CASCADE,
    CODE_HASH CHAR(64) NOT NULL,
    CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (USUARIO_ID, CODE_HASH)
);
